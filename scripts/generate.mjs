import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export function generate() {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const header = readFileSync(`${root}native/contract.h`, 'utf8');
  const names = ['TokenKind', 'NodeKind', 'ErrorCode', 'TypeKind'];
  let output = '// Generated by scripts/generate.mjs from native/contract.h.\n';
  for (const name of names) {
    const body = header.match(new RegExp(`enum ${name} : U32 \\{([^}]+)\\}`))?.[1];
    if (!body) throw new Error(`Missing ABI enum: ${name}`);
    const entries = [...body.matchAll(/(\w+)\s*=\s*(\d+)/g)];
    output += `export const ${name} = {\n`;
    for (const [, key, value] of entries) output += `  ${key}: ${value},\n`;
    output += `} as const;\nexport type ${name} = typeof ${name}[keyof typeof ${name}];\n`;
  }
  writeFileSync(`${root}src/schema.ts`, output);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) generate();
